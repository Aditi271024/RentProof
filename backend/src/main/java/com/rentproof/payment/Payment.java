package com.rentproof.payment;

import java.sql.Date;
import java.sql.Timestamp;

/**
 * Payment model class representing a rent payment transaction in the RentProof system.
 * Module: Payment Management
 * Author: Aanvi
 * 
 * Concepts used (Syllabus up to Lecture 42):
 * - Classes and Objects
 * - Encapsulation (private attributes, public getters and setters)
 * - Constructors (Default, Parameterized, Overloaded)
 * - Comparable interface (sorting payment records chronologically)
 * - Wrapper and Primitive data types (int, double)
 * - toString() method override
 */
public class Payment implements Comparable<Payment> {

    // Database Primary and Foreign Keys
    private int paymentId;
    private int tenantId;
    private int propertyId;
    private int roomId;

    // Payment Financial & Transaction Details
    private double amount;
    private String paymentDate;      // Stored as 'YYYY-MM-DD' String for clean UI/JSON handling
    private String paymentMonth;     // e.g., 'November 2026'
    private String paymentMode;      // 'UPI', 'Bank Transfer', 'Cash', 'Cheque'
    private String transactionRef;   // Reference ID (UPI Ref, UTR, Cheque No, etc.)
    private String paymentStatus;    // 'Paid', 'Pending', 'Overdue', 'Failed'
    private String remarks;          // Optional notes
    private Timestamp createdAt;     // Timestamp generated by database

    // Relational Display Helpers (Populated via SQL JOINs for User-Friendly Display)
    private String tenantName;
    private String propertyName;
    private String roomNumber;

    /**
     * Default Constructor
     */
    public Payment() {
        this.paymentStatus = "Paid";
    }

    /**
     * Parameterized Constructor without paymentId (Used when creating a new payment before inserting into DB)
     */
    public Payment(int tenantId, int propertyId, int roomId, double amount, 
                   String paymentDate, String paymentMonth, String paymentMode, 
                   String transactionRef, String paymentStatus, String remarks) {
        this.tenantId = tenantId;
        this.propertyId = propertyId;
        this.roomId = roomId;
        this.amount = amount;
        this.paymentDate = paymentDate;
        this.paymentMonth = paymentMonth;
        this.paymentMode = paymentMode;
        this.transactionRef = transactionRef;
        this.paymentStatus = (paymentStatus != null && !paymentStatus.trim().isEmpty()) ? paymentStatus : "Paid";
        this.remarks = remarks;
    }

    /**
     * Full Parameterized Constructor with paymentId and createdAt (Used when reading existing records from MySQL)
     */
    public Payment(int paymentId, int tenantId, int propertyId, int roomId, double amount, 
                   String paymentDate, String paymentMonth, String paymentMode, 
                   String transactionRef, String paymentStatus, String remarks, Timestamp createdAt) {
        this.paymentId = paymentId;
        this.tenantId = tenantId;
        this.propertyId = propertyId;
        this.roomId = roomId;
        this.amount = amount;
        this.paymentDate = paymentDate;
        this.paymentMonth = paymentMonth;
        this.paymentMode = paymentMode;
        this.transactionRef = transactionRef;
        this.paymentStatus = paymentStatus;
        this.remarks = remarks;
        this.createdAt = createdAt;
    }

    /**
     * Extended Constructor including joined relational names (Used for table listings & receipts)
     */
    public Payment(int paymentId, int tenantId, int propertyId, int roomId, double amount, 
                   String paymentDate, String paymentMonth, String paymentMode, 
                   String transactionRef, String paymentStatus, String remarks, Timestamp createdAt,
                   String tenantName, String propertyName, String roomNumber) {
        this(paymentId, tenantId, propertyId, roomId, amount, paymentDate, paymentMonth, paymentMode, transactionRef, paymentStatus, remarks, createdAt);
        this.tenantName = tenantName;
        this.propertyName = propertyName;
        this.roomNumber = roomNumber;
    }

    // ==========================================
    // GETTERS AND SETTERS (Encapsulation)
    // ==========================================

    public int getPaymentId() {
        return paymentId;
    }

    public void setPaymentId(int paymentId) {
        this.paymentId = paymentId;
    }

    public int getTenantId() {
        return tenantId;
    }

    public void setTenantId(int tenantId) {
        this.tenantId = tenantId;
    }

    public int getPropertyId() {
        return propertyId;
    }

    public void setPropertyId(int propertyId) {
        this.propertyId = propertyId;
    }

    public int getRoomId() {
        return roomId;
    }

    public void setRoomId(int roomId) {
        this.roomId = roomId;
    }

    public double getAmount() {
        return amount;
    }

    public void setAmount(double amount) {
        this.amount = amount;
    }

    public String getPaymentDate() {
        return paymentDate;
    }

    public void setPaymentDate(String paymentDate) {
        this.paymentDate = paymentDate;
    }

    public String getPaymentMonth() {
        return paymentMonth;
    }

    public void setPaymentMonth(String paymentMonth) {
        this.paymentMonth = paymentMonth;
    }

    public String getPaymentMode() {
        return paymentMode;
    }

    public void setPaymentMode(String paymentMode) {
        this.paymentMode = paymentMode;
    }

    public String getTransactionRef() {
        return transactionRef;
    }

    public void setTransactionRef(String transactionRef) {
        this.transactionRef = transactionRef;
    }

    public String getPaymentStatus() {
        return paymentStatus;
    }

    public void setPaymentStatus(String paymentStatus) {
        this.paymentStatus = paymentStatus;
    }

    public String getRemarks() {
        return remarks;
    }

    public void setRemarks(String remarks) {
        this.remarks = remarks;
    }

    public Timestamp getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Timestamp createdAt) {
        this.createdAt = createdAt;
    }

    public String getTenantName() {
        return tenantName != null ? tenantName : ("Tenant #" + tenantId);
    }

    public void setTenantName(String tenantName) {
        this.tenantName = tenantName;
    }

    public String getPropertyName() {
        return propertyName != null ? propertyName : ("Property #" + propertyId);
    }

    public void setPropertyName(String propertyName) {
        this.propertyName = propertyName;
    }

    public String getRoomNumber() {
        return roomNumber != null ? roomNumber : ("Room #" + roomId);
    }

    public void setRoomNumber(String roomNumber) {
        this.roomNumber = roomNumber;
    }

    // ==========================================
    // OVERRIDDEN OBJECT METHODS
    // ==========================================

    /**
     * Implements Comparable to sort payments in reverse chronological order (newest first).
     * If dates match, sort by payment ID descending.
     */
    @Override
    public int compareTo(Payment other) {
        if (other == null) {
            return 1;
        }
        if (this.paymentDate != null && other.paymentDate != null) {
            int dateComparison = other.paymentDate.compareTo(this.paymentDate);
            if (dateComparison != 0) {
                return dateComparison;
            }
        }
        return Integer.compare(other.paymentId, this.paymentId);
    }

    @Override
    public String toString() {
        return "Payment{" +
                "id=" + paymentId +
                ", tenant='" + getTenantName() + '\'' +
                ", property='" + getPropertyName() + '\'' +
                ", room='" + getRoomNumber() + '\'' +
                ", amount=" + amount +
                ", date='" + paymentDate + '\'' +
                ", month='" + paymentMonth + '\'' +
                ", mode='" + paymentMode + '\'' +
                ", status='" + paymentStatus + '\'' +
                ", ref='" + transactionRef + '\'' +
                '}';
    }
}

